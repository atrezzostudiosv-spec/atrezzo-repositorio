import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {join,dirname} from "node:path";
import {fileURLToPath} from "node:url";
const root=join(dirname(fileURLToPath(import.meta.url)),"..");
const registry=JSON.parse(readFileSync(join(root,"registry/components.json"),"utf8"));
const sticky=registry.entries.filter(e=>e.id.startsWith("ATZ-STK-"));
assert.equal(sticky.length,15,"Approved StickySections source has 15 variants");
assert.equal(new Set(sticky.map(e=>e.id)).size,15);
assert.equal(new Set(sticky.map(e=>e.variant)).size,15);
assert.equal(sticky.every(e=>e.interaction==="scroll"&&e.uses_sticky),true,"Effects must be scroll-driven, not click-driven");
const css=readFileSync(join(root,"components/runtime/atrezzo-sticky.css"),"utf8");
assert(css.includes(".atz-sticky .content--sticky"));
assert(!/(^|\n)\s*(body|html)\s*\{/.test(css),"No global document style overrides");
assert(css.includes("prefers-reduced-motion:reduce"));
const lifecycle=readFileSync(join(root,"components/runtime/sticky-lifecycle.js"),"utf8");
assert(lifecycle.includes("ScrollTrigger.refresh()"));
assert(lifecycle.includes("context.revert()"),"Must destroy GSAP context per instance");
assert(!lifecycle.includes("new Lenis("),"Global Lenis must not be forced on client site");
for(const e of sticky){
 const markup=readFileSync(join(root,e.component_html),"utf8");
 assert(markup.includes('data-atz-id="'+e.id+'"'),e.id+" missing identity");
 assert.equal((markup.match(/content--sticky/g)||[]).length,6,e.id+" must preserve six sticky panels");
 assert.equal((markup.match(/class="content__img /g)||[]).length,6,e.id+" must preserve six images");
 assert(markup.includes("data:image/svg+xml,"),"Reference images must be approved original abstract placeholders");
 assert(!markup.includes("src=\"img/"),e.id+" must not reference unlicensed original PNG assets");
 const code=readFileSync(join(root,e.component_js),"utf8");
 assert(code.includes("../runtime/sticky-lifecycle.js"),e.id+" must use shared controller");
 assert(code.includes("scrollTrigger:"),e.id+" must be ScrollTrigger controlled");
 assert(code.includes("scrub:true"),e.id+" must be scrubbed by scroll");
 assert(!code.includes("document.querySelector"),e.id+" must not target global source DOM");
 assert(!code.includes("new Lenis("),e.id+" must not enable Lenis globally");
 assert.equal(e.client_ready,false);
 assert.equal(e.status,"validation");
 const mod=await import("../"+e.component_js);
 assert.equal(mod.id,e.id);
 assert.equal(mod.variant,Number(e.variant.slice(4)));
 assert.equal(typeof mod.mount,"function");
}
console.log("PASS StickySections 15: exact individual JS modules, six panels, CSS scope, scroll-driven GSAP, reduced-motion, MIT reference, no forced Lenis.");