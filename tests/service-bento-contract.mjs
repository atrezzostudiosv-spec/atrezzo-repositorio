import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolveComponent,createIntegrationPrompt} from "../scripts/resolve-component.mjs";
const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const id="ATZ-SVC-001",e=resolveComponent(id);
assert.equal(e.id,id);
assert.equal(e.category,"servicios");
assert.equal(e.client_ready,false);
assert.equal(e.files.html,"components/servicios/ATZ-SVC-001.html");
assert.equal(e.files.js,"components/servicios/ATZ-SVC-001.js");
assert.equal(e.files.css,"components/servicios/ATZ-SVC-001.css");
assert.equal(e.files.runtime,"components/servicios/runtime.js");
assert.equal(e.assets.length,5);
const html=read(e.files.html),css=read(e.files.css),runtime=read(e.files.runtime);
assert(html.includes('data-atz-id="'+id+'"'),"Service Bento must have scoped root");
assert.equal((html.match(/data-svc-card/g)||[]).length,5,"One featured + four small cards");
assert.equal((html.match(/data-svc-index/g)||[]).length,5);
assert.equal((html.match(/<article\b/g)||[]).length,5,"Semantic articles, not repeated generic cards");
assert.equal((html.match(/class="atz-svc__secondary"/g)||[]).length,1);
assert.equal((html.match(/class="atz-svc__feature/g)||[]).length,0,"Unexpected duplicated feature class");
assert(html.includes("atz-svc__feature"),"One dominant service needed");
assert.equal((html.match(/<a\b/g)||[]).length,11,"Five service links, one all-services link and five demo destinations");
for(let i=1;i<=5;i++){
 const path="components/servicios/illustration-"+String(i).padStart(2,"0")+".svg";
 assert(e.assets.includes(path));
 assert(read(path).startsWith("<svg"),"Only original SVG demo placeholders");
 assert(html.includes('src="illustration-'+String(i).padStart(2,"0")+'.svg"'));
}
assert(css.includes("grid-template-columns:minmax(0,1.24fr) minmax(0,1fr)"));
assert(css.includes("grid-template-columns:repeat(2,minmax(0,1fr))"));
assert(css.includes("@media(max-width:767px)"));
assert(css.includes("scroll-snap-type:x mandatory"));
assert(css.includes("700ms cubic-bezier(.33,0,.2,1)"));
assert(css.includes("prefers-reduced-motion:reduce"));
assert(runtime.includes("IntersectionObserver"));
assert(runtime.includes('keydown'));
assert(runtime.includes("destroy()"));
assert(!runtime.includes("document.querySelector("),"No global document selection");
assert(!runtime.includes("document.body"),"No body mutation");
assert(!runtime.includes("preventDefault()")||runtime.includes('event.target!==rail'),"Only focused rail can intercept arrow key");
assert(!html.includes("home-gallery-feature.jpg")&&!html.includes("home-hero-960.webp"),"Original Tri-Lane photos must stay excluded");
assert(createIntegrationPrompt(id).includes("illustration-05.svg"),"AI integration prompt should list demo assets");
console.log("PASS ATZ-SVC-001: provenance-safe Service Bento 1+4, exact 5 original SVG placeholders, responsive snap, keyboard, reveal, reduced-motion and export contract.");
